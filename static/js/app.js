// Dashboard Logic
async function initDashboard() {
    dashboardMap = L.map('map').setView([11.1271, 78.6569], 7);

    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        attribution: '© OpenStreetMap'
    }).addTo(dashboardMap);

    markerLayer = L.layerGroup().addTo(dashboardMap);

    const resp = await fetch('/api/reports');
    const reports = await resp.json();

    renderPriorityList(reports);

    const districtData = {};
    const heatPoints = [];

    reports.forEach(report => {
        const color = report.risk_category === 'Critical' ? 'red' :
            report.risk_category === 'High' ? 'orange' :
                report.risk_category === 'Medium' ? 'yellow' : 'green';

        const marker = L.circleMarker([report.location.lat, report.location.lng], {
            radius: 8, fillColor: color, color: "#fff", weight: 1, opacity: 1, fillOpacity: 0.8
        });

        marker.bindPopup(`
            <div class="popup-content" style="color:#000">
                <strong>${report.district} - ${report.risk_category}</strong><br>
                Risk Score: ${report.risk_score}<br>
                Status: ${report.status}<br>
                <div style="margin-top:10px">
                    <button class="btn-secondary" style="color:#000" onclick="updateReportStatus('${report._id}', 'In Progress')">${translations[currentLang].in_progress}</button>
                    <button class="btn-secondary" style="color:#000" onclick="updateReportStatus('${report._id}', 'Completed')">${translations[currentLang].fixed}</button>
                </div>
            </div>
        `);
        marker.addTo(markerLayer);

        heatPoints.push([report.location.lat, report.location.lng, report.risk_score / 100]);

        districtData[report.district] = districtData[report.district] || { totalScore: 0, count: 0 };
        districtData[report.district].totalScore += report.risk_score;
        districtData[report.district].count += 1;
    });

    heatmapLayer = L.heatLayer(heatPoints, { radius: 25, blur: 15, maxZoom: 17 });

    renderCharts(reports, districtData);
    fetchStats();
}

function toggleHeatmap() {
    isHeatmapActive = !isHeatmapActive;
    if (isHeatmapActive) {
        dashboardMap.removeLayer(markerLayer);
        heatmapLayer.addTo(dashboardMap);
    } else {
        dashboardMap.removeLayer(heatmapLayer);
        markerLayer.addTo(dashboardMap);
    }
}

async function fetchStats() {
    const resp = await fetch('/api/stats');
    const data = await resp.json();
    const el = document.getElementById('avg-repair-time');
    if (el) el.innerText = `${data.avg_response_time} days`;
}

function renderCharts(reports, districtData) {
    const ctxBar = document.getElementById('district-chart').getContext('2d');
    new Chart(ctxBar, {
        type: 'bar',
        data: {
            labels: Object.keys(districtData),
            datasets: [{
                label: 'Avg Risk Score',
                data: Object.values(districtData).map(d => (d.totalScore / d.count).toFixed(1)),
                backgroundColor: 'rgba(59, 130, 246, 0.8)'
            }]
        },
        options: { responsive: true, plugins: { legend: { display: false } }, scales: { y: { beginAtZero: true } } }
    });

    const categories = { 'Low': 0, 'Medium': 0, 'High': 0, 'Critical': 0 };
    reports.forEach(r => categories[r.risk_category]++);

    const ctxPie = document.getElementById('risk-chart').getContext('2d');
    new Chart(ctxPie, {
        type: 'doughnut',
        data: {
            labels: Object.keys(categories),
            datasets: [{
                data: Object.values(categories),
                backgroundColor: ['#22c55e', '#eab308', '#ef4444', '#7f1d1d']
            }]
        },
        options: { responsive: true, cutout: '70%' }
    });
}

async function updateReportStatus(id, status) {
    const resp = await fetch('/api/update_status', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id, status })
    });
    if (resp.ok) location.reload();
}
