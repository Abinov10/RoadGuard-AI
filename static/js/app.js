function initUploadMap() {
    const defaultPos = [11.1271, 78.6569]; // TN Center
    uploadMap = L.map('upload-map').setView(defaultPos, 7);

    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        attribution: '© OpenStreetMap'
    }).addTo(uploadMap);

    uploadMarker = L.marker(defaultPos, { draggable: true }).addTo(uploadMap);

    function updateCoords(lat, lng) {
        document.getElementById('latitude').value = lat.toFixed(6);
        document.getElementById('longitude').value = lng.toFixed(6);
    }

    uploadMarker.on('dragend', (e) => {
        const pos = e.target.getLatLng();
        updateCoords(pos.lat, pos.lng);
    });

    uploadMap.on('click', (e) => {
        uploadMarker.setLatLng(e.latlng);
        updateCoords(e.latlng.lat, e.latlng.lng);
    });

    if (navigator.geolocation) {
        navigator.geolocation.getCurrentPosition(pos => {
            const loc = [pos.coords.latitude, pos.coords.longitude];
            uploadMap.setView(loc, 15);
            uploadMarker.setLatLng(loc);
            updateCoords(loc[0], loc[1]);
        });
    }
}

// File Preview
const fileInput = document.getElementById('file-input');
const preview = document.getElementById('preview');
const dropText = document.getElementById('drop-text');

if (fileInput) {
    fileInput.addEventListener('change', () => {
        const file = fileInput.files[0];
        if (file) {
            const reader = new FileReader();
            reader.onload = e => {
                preview.src = e.target.result;
                preview.style.display = 'block';
                dropText.style.display = 'none';
            };
            reader.readAsDataURL(file);
        }
    });
}

// Form Submission
const uploadForm = document.getElementById('upload-form');
if (uploadForm) {
    uploadForm.addEventListener('submit', async (e) => {
        e.preventDefault();
        const formData = new FormData(uploadForm);

        formData.set('priority_zone', document.getElementById('priority_zone').checked);
        formData.set('bike_density', document.getElementById('bike_density').checked);

        const btn = document.getElementById('btn-submit');
        btn.disabled = true;
        btn.innerText = translations[currentLang].analyzing;

        try {
            const resp = await fetch('/upload', { method: 'POST', body: formData });
            const data = await resp.json();
            if (data.error) alert(data.error);
            else showResult(data);
        } catch (err) {
            alert("Upload failed.");
        } finally {
            btn.disabled = false;
            btn.innerText = translations[currentLang].btn_submit;
        }
    });
}

function showResult(data) {
    document.getElementById('result-section').style.display = 'block';
    document.getElementById('annotated-img').src = `/static/uploads/${data.detection.annotated_image}`;

    const risk = data.risk;
    document.getElementById('score-value').innerText = risk.risk_score;
    const badge = document.getElementById('risk-badge');
    badge.innerText = risk.risk_category;
    badge.className = `badge ${risk.risk_category}`;

    document.getElementById('damage-type').innerText = data.detection.detections.length > 0
        ? data.detection.detections[0].class : "Surface Wear";
    document.getElementById('severity-value').innerText = `${data.detection.total_severity.toFixed(1)}%`;
    document.getElementById('result-section').scrollIntoView({ behavior: 'smooth' });
}

// User-specific report tethering
async function fetchUserReports() {
    const listEl = document.getElementById('report-status-list');
    if (!listEl) return;

    const resp = await fetch('/api/reports');
    const reports = await resp.json();

    // In a real app, we'd filter by logged-in user email. 
    // For this simulation, we show all but label them.
    listEl.innerHTML = reports.map(r => `
        <div class="report-item glass mb-2 p-3 d-flex justify-content-between align-items-center">
            <div>
                <strong>${r.district}</strong> - ${r.risk_category} Risk
                <br><small>${r.timestamp}</small>
            </div>
            <div class="status-badge ${r.status.replace(' ', '-').toLowerCase()}">
                ${r.status}
            </div>
        </div>
    `).join('') || '<p>No reports found.</p>';
}

// Consultancy Priority List (Revenue Feature)
async function renderPriorityList(reports) {
    const listEl = document.getElementById('priority-list');
    if (!listEl) return;

    // Filter and sort by highest risk for contractors
    const sorted = [...reports].sort((a, b) => b.risk_score - a.risk_score);

    listEl.innerHTML = sorted.slice(0, 5).map((r, i) => `
        <div class="priority-card glass mb-3 p-3" style="border-left: 5px solid ${r.risk_score > 75 ? '#ef4444' : '#eab308'}">
            <div class="d-flex justify-content-between">
                <span>#${i + 1} Priority: ${r.district}</span>
                <span class="badge ${r.risk_category}">${r.risk_score} CRRS</span>
            </div>
            <p class="mt-2 mb-1"><small>Resource Optimization: Plan ${r.risk_score > 80 ? 'Immediate Mobilization' : 'Grouped Maintenance'}</small></p>
            <div class="progress" style="height: 5px; background: rgba(255,255,255,0.1)">
                <div class="progress-bar" style="width: ${r.risk_score}%"></div>
            </div>
        </div>
    `).join('');
}

